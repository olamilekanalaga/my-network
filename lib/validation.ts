import { z } from "zod";
import { photoSchema, profileLinksSchema } from "./profile-media";
import { stages } from "./types";
const s = z.string().max(20000),
  id = z.uuid(),
  ids = z.array(id).max(2000),
  arr = z.array(z.string().max(1000)).max(100);
const status = z.enum(["Confirmed", "Publicly observed", "Inferred"]);
const amount = z.number().min(0).max(1e12).nullable();
export const schemas = {
  people: z.object({
    id,
    name: z.string().trim().min(1).max(200),
    email: s,
    phone: s,
    photo: photoSchema,
    location: s,
    position: s,
    industry: s,
    categories: arr,
    skills: arr,
    services: s,
    building: s,
    needs: s,
    offers: s,
    resources: s,
    links: profileLinksSchema,
    met: s,
    met_date: s,
    notes: s,
    transcript: s,
    promises: s,
    strength: z.number().int().min(1).max(5),
    source: s,
    verification: status,
    updated_at: s,
    consent: s,
  }),
  organizations: z.object({
    id,
    kind: z.enum(["Company", "Community", "Event"]),
    name: z.string().trim().min(1).max(200),
    industry: s,
    location: s,
    description: s,
    capabilities: s,
    needs: s,
    website: s,
    event_date: s,
    notes: s,
  }),
  affiliations: z.object({ id, person_id: id, organization_id: id, role: s }),
  relationships: z
    .object({
      id,
      from_id: id,
      to_id: id,
      label: z.string().min(1).max(500),
      verification: status,
      source: s,
    })
    .refine((x) => x.from_id !== x.to_id, "Choose two different records"),
  facts: z.object({
    id,
    person_id: id,
    text: z.string().min(1).max(20000),
    source_url: s,
    observed_at: s,
    confidence: z.number().min(0).max(1),
    status: z.enum(["pending", "approved"]),
    verification: status,
    visibility: z.enum(["private", "public", "shareable"]),
  }),
  transactions: z.object({
    id,
    person_id: id,
    description: z.string().min(1).max(1000),
    amount: z.number().min(0).max(1e12),
    currency: z.string().regex(/^[A-Z]{3}$/),
    date: s,
    direction: z.enum(["received", "paid"]),
    notes: s,
  }),
  opportunities: z.object({
    id,
    title: z.string().min(1).max(300),
    status: z.enum(stages),
    person_ids: ids,
    organization_ids: ids,
    value: amount,
    potential_fee: amount,
    agreed_fee: amount,
    follow_up: s,
    notes: s,
    outcome: s,
  }),
  activities: z.object({
    id,
    person_id: id.nullable(),
    opportunity_id: id.nullable(),
    text: z.string().min(1).max(20000),
    date: s,
    done: z.boolean(),
  }),
};
